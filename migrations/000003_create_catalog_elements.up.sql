CREATE TABLE meta_catalog_elements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    catalog_id BIGINT NOT NULL,
    code VARCHAR(255) NOT NULL,
    name VARCHAR(255) NOT NULL,

    CONSTRAINT meta_catalog_elements_catalog_fk
        FOREIGN KEY (catalog_id)
        REFERENCES meta_catalogs (id),

    CONSTRAINT meta_catalog_elements_code_unique
        UNIQUE (catalog_id, code),

    CONSTRAINT meta_catalog_elements_name_not_empty
        CHECK (btrim(name) <> '')
);
