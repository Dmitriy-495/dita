CREATE SCHEMA IF NOT EXISTS meta;
CREATE SCHEMA IF NOT EXISTS data;

CREATE TABLE meta.actors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT actors_code_not_empty CHECK (btrim(code) <> ''),
    CONSTRAINT actors_name_not_empty CHECK (btrim(name) <> '')
);

CREATE TABLE meta.configurations (
    id UUID PRIMARY KEY,
    code TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL,
    installed_version TEXT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT configurations_code_not_empty CHECK (btrim(code) <> ''),
    CONSTRAINT configurations_name_not_empty CHECK (btrim(name) <> '')
);

CREATE TABLE meta.configuration_versions (
    configuration_id UUID NOT NULL,
    version TEXT NOT NULL,
    format_version TEXT NOT NULL,
    document JSONB NOT NULL,
    checksum TEXT NOT NULL,
    installed_at TIMESTAMPTZ NULL,
    CONSTRAINT configuration_versions_pk PRIMARY KEY (configuration_id, version),
    CONSTRAINT configuration_versions_configuration_fk FOREIGN KEY (configuration_id)
        REFERENCES meta.configurations (id) ON DELETE RESTRICT,
    CONSTRAINT configuration_versions_version_not_empty CHECK (btrim(version) <> ''),
    CONSTRAINT configuration_versions_format_not_empty CHECK (btrim(format_version) <> ''),
    CONSTRAINT configuration_versions_document_object CHECK (jsonb_typeof(document) = 'object'),
    CONSTRAINT configuration_versions_checksum_sha256 CHECK (checksum ~ '^[0-9a-f]{64}$')
);

CREATE TABLE meta.object_types (
    id UUID PRIMARY KEY,
    configuration_id UUID NOT NULL,
    kind TEXT NOT NULL,
    code TEXT NOT NULL,
    name TEXT NOT NULL,
    physical_table TEXT NOT NULL UNIQUE,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT object_types_configuration_fk FOREIGN KEY (configuration_id)
        REFERENCES meta.configurations (id) ON DELETE RESTRICT,
    CONSTRAINT object_types_kind_check CHECK (kind IN ('catalog', 'document', 'planning', 'task', 'note')),
    CONSTRAINT object_types_code_not_empty CHECK (btrim(code) <> ''),
    CONSTRAINT object_types_name_not_empty CHECK (btrim(name) <> ''),
    CONSTRAINT object_types_physical_table_format CHECK (physical_table ~ '^o_[0-9a-f]{32}$'),
    CONSTRAINT object_types_configuration_code_unique UNIQUE (configuration_id, code),
    CONSTRAINT object_types_id_configuration_unique UNIQUE (id, configuration_id)
);

CREATE TABLE meta.attributes (
    id UUID PRIMARY KEY,
    object_type_id UUID NOT NULL,
    code TEXT NOT NULL,
    name TEXT NOT NULL,
    data_type TEXT NOT NULL,
    physical_column TEXT NOT NULL,
    required BOOLEAN NOT NULL DEFAULT FALSE,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    reference_type_id UUID NULL,
    CONSTRAINT attributes_object_type_fk FOREIGN KEY (object_type_id)
        REFERENCES meta.object_types (id) ON DELETE RESTRICT,
    CONSTRAINT attributes_reference_type_fk FOREIGN KEY (reference_type_id)
        REFERENCES meta.object_types (id) ON DELETE RESTRICT,
    CONSTRAINT attributes_data_type_check CHECK (data_type IN (
        'string', 'text', 'integer', 'decimal', 'boolean', 'date', 'datetime', 'reference'
    )),
    CONSTRAINT attributes_code_not_empty CHECK (btrim(code) <> ''),
    CONSTRAINT attributes_name_not_empty CHECK (btrim(name) <> ''),
    CONSTRAINT attributes_physical_column_format CHECK (physical_column ~ '^a_[0-9a-f]{32}$'),
    CONSTRAINT attributes_reference_consistency CHECK ((data_type = 'reference') = (reference_type_id IS NOT NULL)),
    CONSTRAINT attributes_object_type_code_unique UNIQUE (object_type_id, code),
    CONSTRAINT attributes_object_type_column_unique UNIQUE (object_type_id, physical_column)
);

CREATE TABLE meta.number_counters (
    object_type_id UUID NOT NULL,
    year INTEGER NOT NULL,
    last_number BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT number_counters_pk PRIMARY KEY (object_type_id, year),
    CONSTRAINT number_counters_object_type_fk FOREIGN KEY (object_type_id)
        REFERENCES meta.object_types (id) ON DELETE RESTRICT,
    CONSTRAINT number_counters_year_non_negative CHECK (year >= 0),
    CONSTRAINT number_counters_last_number_non_negative CHECK (last_number >= 0)
);

CREATE INDEX object_types_configuration_active_idx ON meta.object_types (configuration_id, active);
CREATE INDEX attributes_reference_type_idx ON meta.attributes (reference_type_id)
    WHERE reference_type_id IS NOT NULL;
